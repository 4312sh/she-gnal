/** 현대 존댓말 어미 — 하나라도 있으면 말투 이탈로 본다 */
const MODERN_ENDINGS =
  /(요|습니다|ㅂ니다|입니다|예요|에요|어요|아요|네요|죠|거든요)[.?!…\s"']*$/m;

/** 하오체 표지 — 하나도 없으면 이탈로 본다 */
const HAO_MARKERS = /(오|소|구려|다오|시다|시오|겠소|이오|군|하지|라오)[.?!…\s"']/;

/** 이 응답을 써도 되는지 검사. 실패하면 호출부가 고정 대사로 폴백한다. */
export function validateReply(text: string): { ok: boolean; reason?: string } {
  const t = text.trim();
  if (!t) return { ok: false, reason: 'empty' };
  if (t.length > 160) return { ok: false, reason: 'too-long' };

  for (const term of FORBIDDEN_TERMS) {
    if (t.includes(term)) return { ok: false, reason: `forbidden:${term}` };
  }
  // 구체 연도 노출
  if (/\b(18|19)\d{2}\b/.test(t)) return { ok: false, reason: 'year' };
  // 이모지 · 자음 반복 · 물결
  if (/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u.test(t)) {
    return { ok: false, reason: 'emoji' };
  }
  if (/(ㅋ{2,}|ㅎ{2,}|ㅠ{2,}|~{2,})/.test(t)) return { ok: false, reason: 'chat-speak' };
  // 현대 존댓말
  if (MODERN_ENDINGS.test(t)) return { ok: false, reason: 'modern' };
  // 하오체 표지가 전혀 없음
  if (!HAO_MARKERS.test(t + ' ')) return { ok: false, reason: 'register' };

  return { ok: true };
}

/** 모델이 붙이기 쉬운 군더더기를 털어낸다 */
export function cleanReply(text: string): string {
  return text
    .trim()
    .replace(/^["'"']+|["'"']+$/g, '')
    .replace(/^\(.*?\)\s*/, '')
    .replace(/^\[.*?\]\s*/, '')
    .replace(/^(나혜석|여인|그녀)\s*[:：]\s*/, '')
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .join(' ');
}
