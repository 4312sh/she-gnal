export type Misread = { word: string; line: string }

const MISREAD_RULES: { re: RegExp; word: (m: string) => string; line: string }[] = [
  {
    re: /(헐|대박|미쳤다|미쳤어|레전드|쩐다|쩔어)/,
    word: (m) => m,
    line: '당신은 지금 놀랐습니까, 아니면 무언가를 칭찬했습니까? 둘 중 하나를 선택해 주십시오.',
  },
  {
    re: /(ㅋ{1,}|ㅎ{2,}|ㅠ{1,}|ㅜ{2,})/,
    word: (m) => m.slice(0, 2),
    line: '반복된 자음이 수신되었습니다. 신호 잡음으로 분류할지, 의미가 있는지 알려 주십시오.',
  },
  {
    re: /(갓생|존맛|킹받|머선|ㄹㅇ|ㅇㅈ|넘사벽|꿀잼|노잼|핵\S)/,
    word: (m) => m,
    line: '그 단어는 제 사전에 없습니다. 원래 길이로 다시 송신해 주십시오.',
  },
  {
    re: /(마음이 아프|마음 아프|배 ?아파|배가 아프|속상|가슴이 아프)/,
    word: (m) => m.replace(/\s/g, ''),
    line: '손상 부위를 특정해 주십시오. 제 시대에는 교체가 가능합니다.',
  },
  {
    re: /(밥 ?먹었|밥은|식사 ?하셨|밥 먹어)/,
    word: () => '밥 먹었어',
    line: '영양 공급 여부를 확인하는 목적을 알려 주십시오. 저는 공급이 필요 없습니다.',
  },
  {
    re: /(죽겠|죽을 것 같|미치겠|돌겠)/,
    word: (m) => m,
    line: '생명 신호에 이상이 있습니까? 송신자의 상태를 보고해 주십시오.',
  },
  {
    re: /(눈이 높|눈치|발이 넓|손이 크)/,
    word: (m) => m,
    line: '신체 기관의 크기에 대한 말입니까? 해석이 어렵습니다.',
  },
]

/** 위기 신호와 겹치는 말("죽고 싶")은 오해로 다루지 않는다 — 호출부가 먼저 거른다 */
export function findMisread(text: string, learned: string[]): Misread | null {
  for (const r of MISREAD_RULES) {
    const m = text.match(r.re)
    if (!m) continue
    const word = r.word(m[0])
    if (learned.includes(word)) continue
    return { word, line: r.line }
  }
  return null
}

/** 화면에 먼저 뜨는 시스템 줄 — 일치율은 매번 5~35 */
export function misreadSystemLine(): string {
  const pct = 5 + Math.floor(Math.random() * 31)
  return `고대어 해석 중… 일치율 ${pct}%`
}

