export function cleanEioReply(t: string): string {
  return t
    .replace(/^\s*(이오|EIO|그녀)\s*[:：]\s*/i, '')
    .replace(/\([^)]*\)|\*[^*]*\*/g, '')
    .replace(/^["'“”‘’「」]+|["'“”‘’「」]+$/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}

export type EioCheck = { ok: true } | { ok: false; reason: string }

export function validateEioReply(t: string): EioCheck {
  if (!t) return { ok: false, reason: 'empty' }
  if (t.length > 180) return { ok: false, reason: 'long' }
  if (/!|！/.test(t)) return { ok: false, reason: 'exclaim' }
  if (/[ㅋㅎㅠㅜ]|~|진짜|완전|대박|것 같아요/.test(t)) return { ok: false, reason: 'modern' }
  if (/(^|\s)(와|헐|우와|아이고)[,.\s]/.test(t)) return { ok: false, reason: 'interjection' }
  if (/(마음|가슴)이 (아프|뛰)/.test(t)) return { ok: false, reason: 'metaphor' }
  if (/\b(20[3-9]\d|2[1-8]\d\d|29[0-8]\d)\b/.test(t)) return { ok: false, reason: 'year' }
  if (/\p{Extended_Pictographic}/u.test(t)) return { ok: false, reason: 'emoji' }
  // 문장 끝이 해요체 · 반말이면 탈락 ('외로움.' 같은 단어 한 마디는 통과). 마지막 문장은 반드시 …다 · …까 · …오
  const chunks = t.split(/[.?…]+/).map((s) => s.trim()).filter((s) => /[가-힣]/.test(s))
  for (const c of chunks) {
    if (/(요|야|어|지|네|아|게|걸|래|니)$/.test(c.replace(/[^가-힣]+$/, ''))) return { ok: false, reason: `tone:${c.slice(-6)}` }
  }
  const tail = (chunks[chunks.length - 1] ?? '').replace(/[^가-힣]+$/, '').slice(-1)
  if (tail && !/[다까오]/.test(tail)) return { ok: false, reason: `tone-end:${tail}` }
  return { ok: true }
}

