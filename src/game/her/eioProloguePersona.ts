let afterIdx = 0

export function eioFallback(phase: EioPhase, userText: string): string {
  if (/(미래|앞날|어떻게 돼|어떻게 되|몇 년 뒤)/.test(userText)) return '그 기록은 열람 권한이 없습니다.'
  if (/(좋아해|사랑|애인|연애)/.test(userText)) return '그 질문은 제 응답 범위 밖입니다. …아직은.'
  const list = FALLBACK[phase]
  if (phase === 'after') {
    afterIdx = (afterIdx + 1) % list.length
    return list[afterIdx]
  }
  return list[0]
}
