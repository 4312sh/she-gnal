export type Ch1Memory = { done: boolean; name?: string; choice?: 'A' | 'B' };

export function openingLines(m: Ch1Memory): string[] {
  if (m.done && m.name) {
    return [
      '어서 오시오. 문이 열려 있었지요.',
      `…잠깐, 그 목소리. 도쿄 하숙방 앞에서 전보를 건네던… ${m.name} 씨 아니오?`,
      m.choice === 'A'
        ? '그때 당신 말대로 아버지를 설득하러 갔었소. 설득은 끝내 못 했지만.'
        : '그때 당신 말대로 돌아가지 않았소. 학비는 내 손으로 벌었고.',
      '그새 여러 해가 흘렀는데, 당신은 하나도 변하지 않았구려. 마침 잘 왔소. 내 그림 좀 봐 주시오.',
    ];
  }
  return [
    '어서 오시오. 문이 열려 있었지요.',
    '그림 보러 오신 분이오? 이 방까지 찾아오는 사람은 드문데.',
    '마침 잘 왔소. 내 그림 좀 봐 주시오.',
  ];
}

